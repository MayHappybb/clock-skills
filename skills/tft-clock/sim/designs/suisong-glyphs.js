/** The plaque's two characters for hour h (0-23): 子初 at 23:00, 子正 at 00:00, 丑初 at 01:00 ... */
export function shichen(h) {
  return BRANCHES[Math.floor(((h + 1) % 24) / 2)] + (h % 2 ? '初' : '正');
}
