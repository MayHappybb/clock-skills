export const SMALL = Object.fromEntries(Object.entries(P).map(([k, rows]) => [k, sprite(rows.join('\n'))]));

/** Width in px of `str` in SMALL caps with `gap` between glyphs (space = 3 px). */
export function smallWidth(str, gap = 1) {
  let w = 0;
  for (const ch of str) w += (ch === ' ' ? 3 : SMALL[ch].w) + gap;
  return w - gap;
}
