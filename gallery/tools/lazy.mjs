// A skill's player.js with an empty design registry: lazy/<id>.js.
//
// A skill's player.js imports designs/index.js, which imports every design
// (seconds for the bigger skills, and again in every worker). The gallery
// loads player.js through this copy instead: the registry import becomes an
// empty object that faces/load.js fills one design at a time, and every other
// import points back at the skill's own js/ files, so the gallery and the
// designs share one copy of each module.

import { readFile } from 'node:fs/promises';
import { join, posix } from 'node:path';
import { SKILLS } from './skills.mjs';

export async function lazyPlayer(id) {
  const s = SKILLS[id];
  const src = await readFile(join(s.sim, 'js', 'player.js'), 'utf8');
  const js = `../../skills/${s.name}/sim/js/`;   // from lazy/<id>.js
  let registries = 0;
  const out = src
    .replace(/\bimport\s+(\w+)\s+from\s*(['"])\.\.\/designs\/index\.js\2\s*;?/, (m, name) => {
      registries++;
      return `const ${name} = {};   // filled one design at a time by faces/load.js`;
    })
    .replace(/(\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)(['"])(\.{1,2}\/[^'"\n]+)\2/g, (m, lead, q, spec) => `${lead}${q}${posix.join(js, spec)}${q}`);
  if (registries !== 1) throw new Error(`${s.name}/sim/js/player.js: expected one "import X from '../designs/index.js'", found ${registries}`);
  return `// Generated by clock-gallery/tools/lazy.mjs from ${s.name}/sim/js/player.js: do not edit.\n${out}`;
}
