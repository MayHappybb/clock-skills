// Extracts the HD44780 (A00) character generator ROM from the CGROM table in the
// CN0295D datasheet, turning the printed dot-matrix table back into 5x8 bitmaps.
//
// Geometry (measured from the embedded 1024x1354 table raster, see tools/probe*.mjs):
//   table cell grid : 16 cols from x=69.1 pitch 59.46 | 16 rows from y=44.0 pitch 81.7
//   cell (c,r)      : char code = c*16 + r
//   dot lattice     : 5 wide x 10 tall, square pitch 7.5 horizontal / 7.444 vertical
//
// Usage: node tools/extract-rom.mjs <table.pgm> [outfile.js]
import { readPGM } from './pgm.mjs';
import { writeFileSync } from 'node:fs';

const X0 = 69.1, DX = 59.46, Y0 = 44.0, DY = 81.7;
const COLS = 16, ROWS = 16;
const DW = 5, DH = 10;          // dot lattice dimensions
const PX = 7.5, PY = 7.444;     // dot pitch (horizontal / vertical)

const src = process.argv[2] ?? '/tmp/rom.pgm';
const out = process.argv[3] ?? 'sim/js/cgrom-a00.js';
const img = readPGM(src);

const darkness = (cx, cy, rad = 2) => {
  let s = 0, n = 0;
  for (let y = Math.round(cy - rad); y <= Math.round(cy + rad); y++) {
    if (y < 0 || y >= img.height) continue;
    for (let x = Math.round(cx - rad); x <= Math.round(cx + rad); x++) {
      if (x < 0 || x >= img.width) continue;
      s += img.data[y * img.width + x]; n++;
    }
  }
  return 255 - s / n; // 0 = white, 255 = black
};

// A dot is "on" when its centre is markedly darker than the empty gray grid.
const DOT_THRESHOLD = 110;

function extract(code) {
  const c = code >> 4, r = code & 15;
  const cx0 = Math.round(X0 + c * DX), cy0 = Math.round(Y0 + r * DY);
  const grid = [];
  for (let j = 0; j < DH; j++) {
    const row = [];
    for (let i = 0; i < DW; i++) {
      const d = darkness(cx0 + 14 + PX * i, cy0 + 6 + PY * j);
      row.push(d >= DOT_THRESHOLD ? 1 : 0);
    }
    grid.push(row);
  }
  return grid;
}

// --- diagnostics: render a few glyphs as ASCII so the result can be eyeballed ---
const preview = (code) => {
  const g = extract(code);
  const ch = code >= 32 && code < 127 ? JSON.stringify(String.fromCharCode(code)) : `0x${code.toString(16).padStart(2, '0')}`;
  const lines = g.map((row) => '  ' + row.map((v) => (v ? '#' : '.')).join(' '));
  return `0x${code.toString(16).padStart(2, '0').toUpperCase()} ${ch}\n${lines.join('\n')}`;
};

if (process.argv.includes('--preview')) {
  const codes = [0x21, 0x24, 0x38, 0x41, 0x54, 0x70, 0x67, 0x6a, 0x2e, 0x3a];
  console.log(codes.map(preview).join('\n\n'));
  process.exit(0);
}

// --- full extraction ---
const rom = [];
for (let code = 0; code < 256; code++) rom.push(extract(code));

// Codes 0x00-0x0F are CGRAM, not ROM: the table's first column holds the
// printed labels "CG RAM (1)".."(8)" twice over (bit 3 of the code is ignored),
// and sampling those labels as dots produces junk. Blank the whole column.
for (let code = 0; code < 16; code++) rom[code] = Array.from({ length: DH }, () => new Array(DW).fill(0));

// Report which lattice rows are ever used, to confirm the true glyph height.
const rowUse = new Array(DH).fill(0);
for (const g of rom) for (let j = 0; j < DH; j++) if (g[j].some((v) => v)) rowUse[j]++;
console.log('lattice rows used by any glyph:', rowUse.join(' '));

// Pack the lattice into bytes, one byte per dot row, bit4 = leftmost dot.
// This is the HD44780's own CGRAM packing, so ROM and custom glyphs share a
// representation. The datasheet draws a 5x10 lattice; rows 0..7 are the 5x8
// character cell the module actually displays (row 7 doubles as the cursor
// line), and rows 8..9 are only reached by nine descender katakana.
const bytes = [];
for (let code = 0; code < 256; code++) {
  const g = rom[code];
  for (let j = 0; j < DH; j++) {
    let b = 0;
    for (let i = 0; i < DW; i++) if (g[j][i]) b |= 0x10 >> i;
    bytes.push(b);
  }
}

const js = `// HD44780 CGROM font, ROM code A00.
// Generated by tools/extract-rom.mjs from the CGROM table (Table 2) of the
// CN0295D datasheet -- do not edit by hand.
//
// Layout: 256 characters x ${DH} dot rows. One byte per row; bit 4 is the leftmost
// dot, bit 0 the rightmost. Rows 0..7 are the 5x8 character cell the module
// displays; rows 8..9 are reached only by a few descender katakana.
// This is the HD44780's own CGRAM packing, so ROM and CGRAM glyphs are
// interchangeable everywhere in the simulator.
export const CGROM_ROWS = ${DH};
export const CGROM_A00 = new Uint8Array([
${Array.from({ length: 256 }, (_, c) =>
  '  ' + bytes.slice(c * DH, c * DH + DH).map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ') + `, // 0x${c.toString(16).padStart(2, '0')}`,
).join('\n')}
]);
`;
writeFileSync(out, js);
console.log(`wrote ${out} (${bytes.length} bytes)`);