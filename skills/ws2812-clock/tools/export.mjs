// The layout as a C header for firmware: where every LED is, in data order.
//
//   node tools/export.mjs --layout hex [--out leds_hex.h]
//
// Positions are in 0.1 mm from the layout's centre, x right, y down, seen
// from the front. Index = position in the data stream, lane by lane. The
// wire order of each LED's bytes is G, R, B (FastLED: GRB), except on the
// ESP32-S3-Matrix (R, G, B).
//
// HUB75 boards are not a stream: their LEDs are frame-buffer pixels. On a
// layout that is one square lattice the header also gives GX / GY, the pixel
// each index lands on (for drawPixel on a VirtualMatrixPanel of GRID_W x
// GRID_H). Build the firmware with NO_CIE1931: design values are linear.

import { writeFile } from 'node:fs/promises';
import { parseArgs } from './render.mjs';
import { layout } from '../sim/js/layout.js';

const args = parseArgs(process.argv.slice(2));
if (!args.layout) { console.error('usage: node tools/export.mjs --layout <key> [--out file.h]'); process.exit(2); }
const L = layout(args.layout);
const id = args.layout.replace(/[^a-z0-9]/gi, '_').toUpperCase();
const arr = (type, name, vals) => {
  const lines = [];
  for (let i = 0; i < vals.length; i += 16) lines.push('  ' + vals.slice(i, i + 16).join(', ') + ',');
  return `static const ${type} ${name}[${vals.length}] = {\n${lines.join('\n')}\n};\n`;
};
let h = `// ${L.label}: ${L.n} LEDs. Generated by ws2812-clock tools/export.mjs.\n#pragma once\n#include <stdint.h>\n\n`;
h += `#define ${id}_LEDS ${L.n}\n#define ${id}_LANES ${L.lanes.length}\n`;
h += arr('uint16_t', `${id}_LANE_COUNT`, L.lanes.map((l) => l.count));
h += arr('int16_t', `${id}_X`, L.leds.map((l) => Math.round((l.x - L.bbox.cx) * 10)));
h += arr('int16_t', `${id}_Y`, L.leds.map((l) => Math.round((l.y - L.bbox.cy) * 10)));
h += arr('uint8_t', `${id}_BOARD`, L.leds.map((l) => l.panel));
if (L.leds.every((l) => l.ring !== undefined)) {
  h += '// hexagon rings: ring k has 6k LEDs, RINGPOS 0 at 12 o\'clock, clockwise\n';
  h += arr('uint8_t', `${id}_RING`, L.leds.map((l) => l.ring));
  h += arr('uint8_t', `${id}_RINGPOS`, L.leds.map((l) => l.ringPos));
}
for (const p of L.panels) if (p.def.rgbOrder) h += `// board ${p.index} (${p.def.key}): colour order ${p.def.rgbOrder}${p.def.ownMcu ? ', driven by its own MCU' : ''}\n`;
if (L.panels.some((p) => p.def.bus === 'hub75')) h += '// HUB75 boards: indices are pixels; compile ESP32-HUB75-MatrixPanel-DMA with NO_CIE1931 (values are linear)\n';
if (L.grid) h += `#define ${id}_GRID_W ${L.grid.w}\n#define ${id}_GRID_H ${L.grid.h}\n`;
if (L.lattice) {
  h += `// one ${L.lattice.kind} lattice across the layout: integer coordinates\n`;
  h += arr('int16_t', `${id}_GX`, L.leds.map((l) => l.gx));
  h += arr('int16_t', `${id}_GY`, L.leds.map((l) => l.gy));
}
const out = args.out ?? `leds_${args.layout.replace(/[^a-z0-9]/gi, '_')}.h`;
await writeFile(out, h);
console.log(`${out}: ${L.n} LEDs, ${L.lanes.length} lane(s)`);
