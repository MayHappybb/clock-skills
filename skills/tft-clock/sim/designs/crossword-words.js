// crossword: the words. The hour and minute answers, the riddle clues that
// lead to them, and a small crosswordese dictionary of three-letter downs
// (with their clues) that knit the hour row to the minute row.
//
// On the device this is flash data: ~250 three-letter entries and their
// clue strings, a few KB.

import { hash } from '../js/kit.js';

export const HOURS = ['TWELVE', 'ONE', 'TWO', 'THREE', 'FOUR', 'FIVE', 'SIX', 'SEVEN', 'EIGHT', 'NINE', 'TEN', 'ELEVEN'];
const UNITS = ['', 'ONE', 'TWO', 'THREE', 'FOUR', 'FIVE', 'SIX', 'SEVEN', 'EIGHT', 'NINE'];
const TEENS = ['TEN', 'ELEVEN', 'TWELVE', 'THIRTEEN', 'FOURTEEN', 'FIFTEEN', 'SIXTEEN', 'SEVENTEEN', 'EIGHTEEN', 'NINETEEN'];
const TENS = ['', '', 'TWENTY', 'THIRTY', 'FORTY', 'FIFTY'];

/** The minute as crossword answer parts: [['FORTY','SEVEN']] -> 'FORTYSEVEN', enumeration (5,5). */
export function minuteParts(m) {
  if (m === 0) return ['OCLOCK'];
  if (m < 10) return ['OH', UNITS[m]];
  if (m < 20) return [TEENS[m - 10]];
  return UNITS[m % 10] ? [TENS[(m / 10) | 0], UNITS[m % 10]] : [TENS[(m / 10) | 0]];
}
export const minuteWord = (m) => minuteParts(m).join('');
export const hourWord = (h) => HOURS[h % 12];
/** Enumeration as printed after a clue, '(5,5)'; O'CLOCK is (1,5) in a real paper but reads better as (6). */
export const enumOf = (parts) => `(${parts.map((p) => p.length).join(',')})`;

// ------------------------------------------------------------ clues

const NUM = ['NOUGHT', 'ONE', 'TWO', 'THREE', 'FOUR', 'FIVE', 'SIX', 'SEVEN', 'EIGHT', 'NINE', 'TEN', 'ELEVEN', 'TWELVE'];

/** Arithmetic riddles that come to `m`, every one checked; one is picked per minute. */
function minuteRiddles(m) {
  const out = [];
  if (m === 0) return ['ON THE DOT', 'SHARP', 'EXACTLY THE HOUR'];
  if (m === 30) out.push('HALF PAST');
  if (m === 15) out.push('A QUARTER PAST');
  if (m === 45) out.push('THREE QUARTERS');
  if (m === 12) out.push('A DOZEN');
  if (m === 20) out.push('A SCORE');
  if (m > 1 && m % 2 === 0) out.push(`HALF OF ${m * 2}`);
  for (const k of [3, 4, 5, 6, 7, 8, 9]) if (m % k === 0 && m / k > 1 && m / k < 13) out.push(`${NUM[k]} ${NUM[m / k]}S`.replace('SIXS', 'SIXES'));
  if (m > 5) out.push(`${m + 7} LESS SEVEN`);
  if (m > 30) out.push(`${60 - m} TO THE HOUR`);
  if (m > 12) out.push(`DOZEN AND ${m - 12}`);
  if (m >= 1 && m <= 12) out.push(`${NUM[m]} PAST`);
  return out;
}

export function minuteClue(m, minuteKey) {
  const r = minuteRiddles(m);
  return r[hash(minuteKey, 71) % r.length];
}

export function hourClue(h, minuteKey) {
  const n = h % 12 || 12;
  const r = [`THE HOUR`, `${n} ON THE DIAL`, `HOUR HAND AT ${n}`, n === 12 ? 'NOON OR MIDNIGHT' : `${n + 1} LESS ONE`];
  return r[hash(minuteKey, 72) % r.length];
}

