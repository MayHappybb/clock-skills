export const WORDS3 = new Map();
for (const e of DICT.replace(/\n/g, '|').split('|')) {
  const [w, c] = e.split(':');
  if (w && w.length === 3) WORDS3.set(w, c);
}

/** For a top letter and a bottom letter, the middle letters that make a word, as a list (stable order). */
const BRIDGE = new Map();
for (const w of WORDS3.keys()) {
  const k = w[0] + w[2];
  if (!BRIDGE.has(k)) BRIDGE.set(k, []);
  BRIDGE.get(k).push(w);
}
export const bridges = (top, bottom) => BRIDGE.get(top + bottom) ?? [];
