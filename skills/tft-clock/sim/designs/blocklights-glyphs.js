export const GW = 7, GH = 10;

/** GLYPHS[d] is a Uint8Array(GW * GH): 1 where the flat is lit. */
export const GLYPHS = Array.from({ length: 10 }, (_, d) => {
  const g = new Uint8Array(GW * GH);
  ROWS[d].forEach((row, r) => { for (let c = 0; c < GW; c++) g[r * GW + c] = row[c] === '#' ? 1 : 0; });
  return g;
});
