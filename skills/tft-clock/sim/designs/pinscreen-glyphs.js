function rows(src) {
  return src.split('\n').filter((l) => l.length);
}

/**
 * A glyph as cell maps over its box plus a two-pin margin:
 *  m[k]: 1 pin of the numeral, 2 moat (a pin next to one, or in a counter), 0 free
 *  e[k]: for numeral pins, 0 on the outline, 1 inside (the order they rise in)
 */
function build(src, W, H) {
  const r = rows(src);
  if (r.length !== H || r.some((l) => l.length !== W)) throw new Error(`pinscreen glyph: bad size ${r.length} rows`);
  const BW = W + 4, BH = H + 4, m = new Uint8Array(BW * BH), e = new Uint8Array(BW * BH);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (r[y][x] === '#') m[(y + 2) * BW + x + 2] = 1;
  const on = (x, y) => x >= 0 && y >= 0 && x < BW && y < BH && m[y * BW + x] === 1;
  for (let y = 0; y < BH; y++)
    for (let x = 0; x < BW; x++) {
      const k = y * BW + x;
      if (m[k] === 1) {
        // outline: any of the 8 neighbours is free
        let edge = 0;
        for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) if (!on(x + dx, y + dy)) edge = 1;
        e[k] = edge ? 0 : 1;
      }
    }
  // free cells cut off from the box's border are counters (flood fill from the edge)
  const out = new Uint8Array(BW * BH), stack = [];
  for (let x = 0; x < BW; x++) stack.push(x, (BH - 1) * BW + x);
  for (let y = 0; y < BH; y++) stack.push(y * BW, y * BW + BW - 1);
  while (stack.length) {
    const k = stack.pop();
    if (out[k] || m[k] === 1) continue;
    out[k] = 1;
    const x = k % BW, y = (k / BW) | 0;
    if (x > 0) stack.push(k - 1);
    if (x < BW - 1) stack.push(k + 1);
    if (y > 0) stack.push(k - BW);
    if (y < BH - 1) stack.push(k + BW);
  }
  // moat: one pin round the outside (the cast shadow does the rest), every counter pin
  for (let y = 0; y < BH; y++)
    for (let x = 0; x < BW; x++) {
      const k = y * BW + x;
      if (m[k] === 1) continue;
      if (!out[k]) { m[k] = 2; continue; }
      let near = 0;
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) if (on(x + dx, y + dy)) near = 1;
      if (near) m[k] = 2;
    }
  return { m, e, bw: BW, bh: BH };
}

function rot180(src) {
  return '\n' + rows(src).reverse().map((l) => [...l].reverse().join('')).join('\n');
}
HOUR[9] = rot180(HOUR[6]);
MIN[9] = rot180(MIN[6]);

export const HOUR_W = 12, HOUR_H = 22, MIN_W = 9, MIN_H = 15;
export const HOUR_GLYPHS = Array.from({ length: 10 }, (_, d) => build(HOUR[d], HOUR_W, HOUR_H));
export const MIN_GLYPHS = Array.from({ length: 10 }, (_, d) => build(MIN[d], MIN_W, MIN_H));
