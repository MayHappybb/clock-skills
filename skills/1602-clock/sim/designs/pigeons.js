import { TileAllocator } from '../js/kit.js';

const G = {
  a: ['.....', '...##', '...#.', '..###', '#####', '.####', '..##.', '..#.#'],
  b: ['.....', '..##.', '..###', '..##.', '#####', '.####', '..##.', '..#..'],
  c: ['.....', '.....', '...##', '..###', '#.###', '.####', '..##.', '..#.#'],
  d: ['.....', '..##.', '..##.', '.###.', '#####', '..###', '..##.', '..#.#'],
  e: ['.....', '.....', '.....', '#..##', '.####', '..###', '..##.', '..#.#'],
  f: ['.....', '.....', '.....', '#....', '.###.', '..###', '..###', '..#.#'],
  g: ['.....', '..##.', '.###.', '.##..', '####.', '#####', '.###.', '..#.#'],
  h: ['.....', '.....', '.##..', '####.', '#####', '#####', '.###.', '.....'],
};

export default {
  name: 'pigeons',
  blurb: 'Placeholder.',
  bus: 'i2c100',
  panel: 'green',
  fps: 10,
  frame(lcd) {
    const a = new TileAllocator(lcd, 0);
    const k = Object.keys(G);
    const codes = k.slice(0, 8).map((n) => a.add(G[n]));
    a.flush();
    codes.forEach((c, i) => { lcd.setCursor(i * 2, 0); lcd.data(c); });
    lcd.setCursor(0, 1); for (const c of codes) lcd.data(c);
  },
};
