// constructivist: the lettering.
//
// DIGITS: hand-cut poster block numerals in the manner of Rodchenko's
// lettering: heavy (stroke = 1/5 of the height), condensed, square counters,
// no curves, a few corners sliced off on the diagonal and a diagonal spine on
// 2, 4 and 7. Each digit is a list of convex polygons on a 6 x 10 grid (y
// down), overlapping where they meet so anti-aliased seams never show. The
// face never draws them upright: every vertex is mapped into the shout cone
// (constructivist.js), so the numerals are wedges that widen away from the
// mouth.
//
// SMALL: a 3-row-stroke bitmap slab caps for the date strip, cut for this
// face (7 px tall, 2 px stems), only the letters the date needs.

