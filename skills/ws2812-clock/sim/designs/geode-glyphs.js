// Ametrine numerals: every stroke is one quartz prism, every loop a hexagon
// (the crystal's own cross-section). Design box 10 x 16 units, y down.
// A segment is [ax, ay, bx, by]: the crystal grows from a to b, in list order.
// Free ends get sharp terminations; joints are blunt and overlap.

const G = {
  0: [[5, 16, 0, 12], [0, 12, 0, 4], [0, 4, 5, 0], [5, 0, 10, 4], [10, 4, 10, 12], [10, 12, 5, 16]],
  1: [[5.6, 16.6, 5.6, -0.6], [5.6, 0.4, 2.2, 3.8]],
  2: [[0, 5.8, 0, 3.6], [0, 3.6, 5, 0], [5, 0, 9.8, 4], [9.8, 4, 9.8, 6], [9.8, 6, 0, 15.6], [0, 15.6, 10.6, 15.6]],
  3: [[0.2, 2.6, 5, 0], [5, 0, 9.8, 3], [9.8, 3, 9.8, 4.6], [9.8, 4.6, 4.2, 7.8], [4.2, 7.8, 10, 11.2],
      [10, 11.2, 10, 12.6], [10, 12.6, 5, 16], [5, 16, -0.2, 13.2]],
  4: [[7.6, 16.6, 7.6, 2.4], [5, -0.6, 0, 11], [0, 11, 10.8, 11]],
  5: [[10.6, 0, 1, 0], [1, 0, 0.6, 7.2], [0.6, 7.2, 5.4, 5.6], [5.4, 5.6, 10, 8.8], [10, 8.8, 10, 12.4],
      [10, 12.4, 5, 16], [5, 16, -0.2, 13.4]],
  6: [[9, -0.6, 0, 9.6], [0, 9.6, 0, 12.6], [0, 12.6, 5, 16], [5, 16, 10, 12.6], [10, 12.6, 10, 9.8],
      [10, 9.8, 5, 6.4], [5, 6.4, 0, 9.6]],
  7: [[-0.6, 0, 10, 0], [10, 0, 2.8, 16.6]],
  8: [[5, 7.6, 9.2, 5.2], [9.2, 5.2, 9.2, 2.4], [9.2, 2.4, 5, 0], [5, 0, 0.8, 2.4], [0.8, 2.4, 0.8, 5.2],
      [0.8, 5.2, 5, 7.6], [5, 7.6, 10, 10.4], [10, 10.4, 10, 13.2], [10, 13.2, 5, 16], [5, 16, 0, 13.2],
      [0, 13.2, 0, 10.4], [0, 10.4, 5, 7.6]],
  9: [[1, 16.6, 10, 6.4], [10, 6.4, 10, 3.4], [10, 3.4, 5, 0], [5, 0, 0, 3.4], [0, 3.4, 0, 6.2],
      [0, 6.2, 5, 9.6], [5, 9.6, 10, 6.4]],
};

const near = (ax, ay, bx, by) => Math.abs(ax - bx) < 0.05 && Math.abs(ay - by) < 0.05;

/** Glyph d as prisms: { ax, ay, bx, by, freeA, freeB } in design units. */
export function glyph(d) {
  const segs = G[d];
  return segs.map((s, i) => {
    let freeA = true, freeB = true;
    segs.forEach((o, j) => {
      if (j === i) return;
      if (near(s[0], s[1], o[0], o[1]) || near(s[0], s[1], o[2], o[3])) freeA = false;
      if (near(s[2], s[3], o[0], o[1]) || near(s[2], s[3], o[2], o[3])) freeB = false;
    });
    return { ax: s[0], ay: s[1], bx: s[2], by: s[3], freeA, freeB };
  });
}
